#!/bin/bash
# Boots the AI17Z guest image and reports what the guest said about itself.
#
#   boot-ai17z-guest.sh <id> [vcpus] [mem_mib]
#
# Everything the guest prints is something it did: Postgres started inside the
# boundary, migrations applied, the api answering its own health endpoint, the
# worker reporting ready, and the memory that actually cost. A plan priced from
# a developer's machine is priced from the wrong machine, so the figure comes
# from inside the guest.
#
# It is given more memory than a confidential floor by default, because the
# first question is whether it runs at all and the second is how little it needs.
set -euo pipefail

ID="${1:-ai17z-tenant}"
VCPUS="${2:-2}"
MEM="${3:-4096}"

LAB=/opt/ai17z-lab
NS="ai17z-$ID"
TAP="tap$(printf %s "$ID" | sha256sum | cut -c1-8)"
LOG="$LAB/$ID.console.log"

say() { printf '  %s\n' "$*"; }

[ -f "$LAB/dl/rootfs-ai17z.ext4" ] || { echo "no AI17Z guest image; run build-ai17z-guest.sh first" >&2; exit 2; }

# Stop anything from a previous run: a guest still up holds its tap.
pkill -f "jailer --id $ID" 2>/dev/null || true
for p in $(pgrep -f firecracker 2>/dev/null || true); do
  if tr '\0' ' ' < "/proc/$p/cmdline" 2>/dev/null | grep -q -- "--id $ID"; then kill -TERM "$p" 2>/dev/null || true; fi
done
sleep 1

ip netns del "$NS" 2>/dev/null || true
ip netns add "$NS"
ip netns exec "$NS" ip link set lo up
ip netns exec "$NS" ip tuntap add dev "$TAP" mode tap
ip netns exec "$NS" ip addr add 172.31.0.1/30 dev "$TAP"
ip netns exec "$NS" ip link set "$TAP" up

# The tenant egress policy, loaded before the guest can send a packet. It is
# generated by AI17Z itself: see tools/hosted-egress-proof.mts.
if [ -f "$LAB/$ID.nft" ]; then
  ip netns exec "$NS" nft -f "$LAB/$ID.nft"
  say "tenant egress policy loaded"
else
  say "no generated ruleset at $LAB/$ID.nft, so this guest is unfiltered: generate one before trusting anything it reaches"
fi

# An uplink, so the guest can reach a package index and the open web the way a
# real tenant's research would. The tenant policy still decides what leaves.
if [ -x "$LAB/bin/uplink.sh" ]; then
  "$LAB/bin/uplink.sh" "$NS" "$TAP" >/dev/null 2>&1 || say "the uplink reported a problem"
fi

getent group ai17zvm >/dev/null || groupadd -r -g 10000 ai17zvm
id -u ai17zvm >/dev/null 2>&1 || useradd -r -u 10000 -g ai17zvm -s /usr/sbin/nologin -M ai17zvm 2>/dev/null

rm -rf "$LAB/jail/$ID"
JAIL="$LAB/jail/$ID/firecracker/$ID/root"
mkdir -p "$JAIL"
cp "$LAB/dl/vmlinux" "$JAIL/vmlinux"
# Copied rather than linked, so each guest writes to its own disk. Two guests
# sharing one writable image is two tenants sharing a filesystem.
cp "$LAB/dl/rootfs-ai17z.ext4" "$JAIL/rootfs.ext4"
cat > "$JAIL/config.json" <<JSON
{
  "boot-source": {
    "kernel_image_path": "vmlinux",
    "boot_args": "console=ttyS0 reboot=k panic=1 pci=off ip=172.31.0.2::172.31.0.1:255.255.255.252::eth0:off init=/ai17z-guest-init.sh"
  },
  "drives": [ { "drive_id": "rootfs", "path_on_host": "rootfs.ext4", "is_root_device": true, "is_read_only": false } ],
  "machine-config": { "vcpu_count": ${VCPUS}, "mem_size_mib": ${MEM}, "smt": false },
  "network-interfaces": [ { "iface_id": "eth0", "host_dev_name": "${TAP}" } ]
}
JSON
chown -R 10000:10000 "$LAB/jail/$ID"

: > "$LOG"
setsid jailer \
  --id "$ID" --exec-file /usr/local/bin/firecracker \
  --uid 10000 --gid 10000 \
  --chroot-base-dir "$LAB/jail/$ID" --netns "/var/run/netns/$NS" \
  -- --config-file config.json --no-api \
  > "$LOG" 2>&1 < /dev/null &

say "booting ${VCPUS} vCPU, ${MEM} MiB, as uid 10000 under the jailer in $NS"

# AI17Z starting is a matter of minutes rather than seconds: initdb, migrations
# and two processes. Waited on rather than slept through.
for _ in $(seq 1 900); do
  grep -q 'AI17Z-GUEST done' "$LOG" 2>/dev/null && break
  sleep 1
done

printf '\n'
if grep -q 'AI17Z-GUEST' "$LOG" 2>/dev/null; then
  grep 'AI17Z-GUEST' "$LOG" | sed 's/AI17Z-GUEST /  /'
else
  say 'the guest said nothing. last of its console:'
  tail -8 "$LOG" | tr -d '\000' | sed 's/^/    /'
fi

FAILED=$(grep -c 'AI17Z-GUEST FAIL' "$LOG" 2>/dev/null || true)
printf '\n'
if [ "${FAILED:-1}" = "0" ] && grep -q 'AI17Z-GUEST done' "$LOG" 2>/dev/null; then
  say 'The canonical AI17Z ran inside the guest.'
  exit 0
fi
say "${FAILED:-?} step(s) failed inside the guest. Its own logs are in the jail at $JAIL."
exit 1
